/* Turns data/days.json into an idempotent INSERT for bd_days.
   The seeded days have to live in the database, not just in the app file:
   that is how taking one increments did_count and how a published day
   remembers which day it came from.

     node scripts/build-seed-sql.mjs > supabase/seed-days.sql

   Re-runnable. Existing rows keep their counts; only the editorial fields
   are refreshed, so nobody's tally is ever reset by a re-seed. */
import { readFileSync } from 'node:fs';
import { validateDay } from '../js/core.js';

const { days } = JSON.parse(readFileSync(new URL('../data/days.json', import.meta.url), 'utf8'));
const q = (v) => v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const arr = (xs) => `'{${(xs ?? []).map((x) => `"${String(x).replace(/"/g, '\\"')}"`).join(',')}}'`;

const rows = [];
for (const d of days) {
  const v = validateDay(d);
  if (!v.ok) { console.error(`refusing ${d.id}: ${v.errs.join(', ')}`); process.exit(1); }
  if (d.stats?.did !== 0) { console.error(`refusing ${d.id}: seeded counts must start at zero`); process.exit(1); }
  const stops = d.stops.map((s) => ({ ref: s.ref, min: s.min, note: s.note ?? null }));
  rows.push(`  (${q(d.id)}, ${q(d.name)}, ${q(d.blurb)}, ${q(d.author)}, true, ${arr(d.wants)}, ` +
            `${q(d.mobility ?? 'normal')}, ${q(d.budget ?? 'any')}, ${arr(d.season)}, ` +
            `${q(JSON.stringify(stops))}::jsonb)`);
}

process.stdout.write(`-- Generated by scripts/build-seed-sql.mjs — do not hand-edit.
-- Re-running is safe: counts are never touched, only the editorial fields.
insert into bd_days (slug, name, blurb, author_name, btown_pick, wants, mobility, budget, season, stops)
values
${rows.join(',\n')}
on conflict (slug) do update set
  name = excluded.name, blurb = excluded.blurb, author_name = excluded.author_name,
  btown_pick = excluded.btown_pick, wants = excluded.wants, mobility = excluded.mobility,
  budget = excluded.budget, season = excluded.season, stops = excluded.stops;
`);
